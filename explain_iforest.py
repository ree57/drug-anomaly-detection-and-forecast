"""Step 8c: why does Isolation Forest flag its top events?

Isolation Forest has no built-in explanation, so we use a simple, honest one: for each of the top 20 test-split
families of a model, take the family's highest-scoring event and compare every feature with the TRAIN events
(the data the forest learned "normal" from):
  - numeric features: percentile among train events; < 1st or > 99th percentile = unusual
  - 0/1 features: how often the event's value occurs in train; < 5% = rare
"Rare but boring" CANDIDATE: a top family whose move is NOT big in absolute terms (abs_log_change within the
train 99th percentile), so it was isolated by context (history, gap, codes, class) or by a z-score inflated by a
flat history. Whether it really is boring needs judgement: some (brand list-price cuts) are real.

Writes reports/iforest_top20.md (needs data/eval/scores_iforest, families and eval_events).
"""
import os
import sys

os.environ["PYSPARK_PYTHON"] = sys.executable
import numpy as np
from pyspark.sql import SparkSession

MODELS = ["if_full", "if_small"]
NUMERIC = ["log_change", "abs_log_change", "z_b_signed_log", "typical_past_move", "weeks_since_last_event",
           "log_old_price", "n_ndcs_priced", "n_distinct_prices"]
BINARY = ["is_brand", "is_january", "after_gap", "class_changed", "has_code_3"]
FEATURES_SMALL = ["abs_log_change", "z_b_signed_log", "typical_past_move"]

spark = (SparkSession.builder.master("local[*]").appName("explain_iforest")
         .config("spark.driver.memory", "4g")
         .config("spark.sql.execution.arrow.pyspark.enabled", "true").getOrCreate())
spark.sparkContext.setLogLevel("ERROR")
spark.read.parquet("data/eval/scores_iforest").createOrReplaceTempView("iforest")
spark.read.parquet("data/eval/families").createOrReplaceTempView("families")
spark.read.parquet("data/eval/eval_events").createOrReplaceTempView("ev")
df = spark.sql("""
    SELECT i.*, f.family_id, e.category, e.pct_change, e.old_price, e.new_price
    FROM iforest i
    JOIN ev e USING (drug_group, published_week)
    JOIN families f USING (drug_group, published_week)
    WHERE e.category NOT LIKE 'excluded%'""").toPandas()
spark.stop()

train = df[(df.split == "train") & ~df.filled_missing]
sorted_train = {c: np.sort(train[c].to_numpy()) for c in NUMERIC}


def describe(row, features):
    """List the features of one event that look unusual compared with the train events."""
    notes, big_move = [], False
    for c in features:
        v = row[c]
        if c in NUMERIC:
            pct = 100 * np.searchsorted(sorted_train[c], v, side="right") / len(sorted_train[c])
            if pct < 1 or pct > 99:
                notes.append(f"{c}={v:.3g} (p{pct:.2f})")
            big_move |= c == "abs_log_change" and pct > 99
        else:
            share = 100 * (train[c] == v).mean()
            if share < 5:
                notes.append(f"{c}={int(v)} (only {share:.1f}% of train)")
    return notes, big_move


lines = ["# Isolation Forest: why the top 20 families are flagged (test split 2025–26)", "",
         "Generated by `explain_iforest.py`. For each family, its highest-scoring event is compared with the",
         "2022–24 training events. Numeric features outside the 1st–99th train percentile and 0/1 values seen in",
         "under 5% of training events are listed. **Candidate rare-but-boring** = the move is not big in absolute",
         "terms (|log change| within the train 99th percentile), so context or a flat-history z isolated it.", ""]
test = df[df.split == "test"]
for model in MODELS:
    feats = FEATURES_SMALL if model == "if_small" else NUMERIC + BINARY
    top_events = test.loc[test.groupby("family_id")[f"score_{model}"].idxmax()]
    sizes = test.groupby("family_id").size()
    top = top_events.sort_values(f"score_{model}", ascending=False).head(20)
    lines += [f"## {model}", "",
              "| # | Event (top member) | Week | Change | Family size | Category | Unusual features | Rare but boring? |",
              "|---|---|---|---|---|---|---|---|"]
    boring = 0
    for i, (_, r) in enumerate(top.iterrows(), 1):
        notes, big_move = describe(r, feats)
        boring += not big_move
        # r["..."] not r.attr: pct_change is also the name of a pandas method
        lines.append(f"| {i} | {r['drug_group']} | {r['published_week']} | {r['pct_change']:+.1f}% "
                     f"(${r['old_price']:.5g} → ${r['new_price']:.5g}) | {sizes[r['family_id']]} | {r['category']} | "
                     f"{'; '.join(notes) or '—'} | {'**candidate**' if not big_move else 'no'} |")
    lines += ["", f"Rare-but-boring candidates in the top 20: **{boring}**", ""]
    print(f"{model}: {boring} of the top 20 families are rare-but-boring candidates")

os.makedirs("reports", exist_ok=True)
with open("reports/iforest_top20.md", "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("saved reports/iforest_top20.md")
